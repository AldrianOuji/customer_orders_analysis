/* ================================================================
   					CUSTOMER & ORDER ANALYSIS
   Purpose: Analyze customer demographics, spending behavior, order
   	activity, revenue performance, retention, and discount patterns.
   ================================================================= */


/* ============================================================
   1. CUSTOMER OVERVIEW
   ============================================================ */

-- Total number of customers
SELECT 
    COUNT(*) AS total_customers
FROM customers;


-- Customer distribution by country
SELECT
    country,
    COUNT(*) AS customer_count
FROM customers
GROUP BY country
ORDER BY customer_count DESC;


-- Customer distribution by membership tier
SELECT
    membership_tier,
    COUNT(*) AS customer_count
FROM customers
GROUP BY membership_tier
ORDER BY customer_count DESC;


/* ============================================================
   2. CUSTOMER VALUE & SPENDING
   ============================================================ */

-- Top 10 customers by total lifetime spend
SELECT
    customer_id,
    country,
    membership_tier,
    ROUND(total_spend_usd, 2) AS total_spend_usd
FROM customers
ORDER BY total_spend_usd DESC
LIMIT 10;


-- Customer-level spending summary
SELECT
    ROUND(AVG(age), 1) AS average_customer_age,
    ROUND(AVG(total_spend_usd), 2) AS average_customer_spend,
    ROUND(SUM(total_spend_usd), 2) AS total_customer_spend
FROM customers;


-- Customer churn summary
SELECT
    COUNT(*) FILTER (WHERE churned = 1) AS churned_customers,
    COUNT(*) AS total_customers,
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE churned = 1) / COUNT(*),
        2
    ) AS churn_rate_pct
FROM customers;


-- High-value customers based on lifetime spend
SELECT
    COUNT(*) AS high_value_customers
FROM customers
WHERE total_spend_usd > 1000;


/* ============================================================
   3. ORDER ACTIVITY
   ============================================================ */

-- Orders placed by each customer
SELECT
    c.customer_id,
    COUNT(o.order_id) AS total_orders
FROM customers AS c
LEFT JOIN orders AS o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id
ORDER BY total_orders DESC;


-- Top 10 customers by order volume
SELECT
    c.customer_id,
    COUNT(o.order_id) AS total_orders
FROM customers AS c
INNER JOIN orders AS o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id
ORDER BY total_orders DESC
LIMIT 10;


/* ============================================================
   4. CUSTOMER REVENUE ANALYSIS
   ============================================================ */

-- Revenue generated by each customer
SELECT
    c.customer_id,
    COUNT(o.order_id) AS total_orders,
    ROUND(SUM(o.total_amount_usd), 2) AS total_revenue
FROM customers AS c
INNER JOIN orders AS o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id
ORDER BY total_revenue DESC;


-- Top 10 customers by order revenue
SELECT
    c.customer_id,
    COUNT(o.order_id) AS total_orders,
    ROUND(SUM(o.total_amount_usd), 2) AS total_revenue
FROM customers AS c
INNER JOIN orders AS o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id
ORDER BY total_revenue DESC
LIMIT 10;


/* ============================================================
   5. PRODUCT PERFORMANCE
   ============================================================ */

-- Revenue by product category
SELECT
    category,
    COUNT(order_id) AS total_orders,
    ROUND(SUM(total_amount_usd), 2) AS total_revenue
FROM orders
GROUP BY category
ORDER BY total_revenue DESC;


-- Average order value by product category
SELECT
    category,
    ROUND(AVG(total_amount_usd), 2) AS average_order_value
FROM orders
GROUP BY category
ORDER BY average_order_value DESC;


/* ============================================================
   6. GEOGRAPHIC REVENUE PERFORMANCE
   ============================================================ */

-- Top 5 countries by revenue
SELECT
    c.country,
    COUNT(DISTINCT o.order_id) AS total_orders,
    ROUND(SUM(o.total_amount_usd), 2) AS total_revenue
FROM customers AS c
INNER JOIN orders AS o
    ON c.customer_id = o.customer_id
GROUP BY c.country
ORDER BY total_revenue DESC
LIMIT 5;


/* ============================================================
   7. MEMBERSHIP TIER PERFORMANCE
   ============================================================ */

-- Revenue contribution by membership tier
SELECT
    c.membership_tier,
    COUNT(DISTINCT c.customer_id) AS customers,
    COUNT(o.order_id) AS total_orders,
    ROUND(SUM(o.total_amount_usd), 2) AS total_revenue
FROM customers AS c
INNER JOIN orders AS o
    ON c.customer_id = o.customer_id
GROUP BY c.membership_tier
ORDER BY total_revenue DESC;


/* ============================================================
   8. HIGH-ENGAGEMENT & HIGH-VALUE CUSTOMERS
   ============================================================ */

-- Customers with more than 5 orders
SELECT
    c.customer_id,
    COUNT(o.order_id) AS total_orders
FROM customers AS c
INNER JOIN orders AS o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id
HAVING COUNT(o.order_id) > 5
ORDER BY total_orders DESC;


-- Customers generating more than $1,000 in order revenue
SELECT
    c.customer_id,
    COUNT(o.order_id) AS total_orders,
    ROUND(SUM(o.total_amount_usd), 2) AS total_revenue
FROM customers AS c
INNER JOIN orders AS o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id
HAVING SUM(o.total_amount_usd) > 1000
ORDER BY total_revenue DESC;


/* ============================================================
   9. CUSTOMER ACQUISITION & RETENTION
   ============================================================ */

-- Repeat customer rate by acquisition channel
SELECT
    c.acquisition_channel,
    COUNT(DISTINCT c.customer_id) AS total_customers,

    COUNT(
        DISTINCT CASE
            WHEN o.is_repeat_customer = TRUE
            THEN c.customer_id
        END
    ) AS repeat_customers,

    ROUND(
        100.0 *
        COUNT(
            DISTINCT CASE
                WHEN o.is_repeat_customer = TRUE
                THEN c.customer_id
            END
        )
        / NULLIF(COUNT(DISTINCT c.customer_id), 0),
        2
    ) AS repeat_customer_rate_pct

FROM customers AS c
LEFT JOIN orders AS o
    ON c.customer_id = o.customer_id

WHERE c.acquisition_channel IS NOT NULL

GROUP BY c.acquisition_channel
ORDER BY repeat_customer_rate_pct DESC;


/* ============================================================
   10. DISCOUNT BEHAVIOR ANALYSIS
   ============================================================ */

-- Examine whether customer lifetime spend and tenure are
-- associated with the discount amount received per order.

WITH customer_metrics AS (
    SELECT
        customer_id,
        total_spend_usd,
        CURRENT_DATE - registration_date AS tenure_days
    FROM customers
)

SELECT
    ROUND(
        CORR(o.discount_amount_usd, cm.total_spend_usd)::NUMERIC,
        4
    ) AS spend_discount_correlation,

    ROUND(
        CORR(o.discount_amount_usd, cm.tenure_days)::NUMERIC,
        4
    ) AS tenure_discount_correlation,

    ROUND(AVG(cm.total_spend_usd), 2) AS average_customer_spend,

    ROUND(AVG(cm.tenure_days), 0) AS average_tenure_days,

    ROUND(AVG(o.discount_amount_usd), 2) AS average_order_discount

FROM orders AS o
INNER JOIN customer_metrics AS cm
    ON o.customer_id = cm.customer_id

WHERE o.discount_amount_usd IS NOT NULL;